def match_barangay(phrase):
    phrase_clean = re.sub(r'\s+', ' ', phrase.strip().lower())
    if not phrase_clean:
        return None
    if phrase_clean in ALIASES:
        return ALIASES[phrase_clean]
    if phrase_clean in barangays:
        return phrase
    for official in bs['barangay']:
        off_lower = official.lower()
        if phrase_clean in off_lower or off_lower in phrase_clean:
            return official
    for alias, official in ALIASES.items():
        if phrase_clean in alias or alias in phrase_clean:
            return official
    return None


unmapped = []
for area in areas:
    if area.upper() == 'OFF':
        continue
    parts = [p.strip() for p in area.split(',') if p.strip()]
    unmatched_parts = [p for p in parts if match_barangay(p) is None]
    if unmatched_parts:
        unmapped.append((area, unmatched_parts))

print(f"Areas with unmapped parts: {len(unmapped)} / {len(areas) - 1}\n")
for area, parts in unmapped:
    print(f"AREA: {area}")
    for p in parts:
        print(f"  UNMAPPED: {p}")
    print()
